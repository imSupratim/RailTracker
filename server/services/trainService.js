export const searchTrain = async (query) => {
  const search = query.trim().toLowerCase();
  const API_KEY = process.env.RAIL_RADAR;

  const response = await fetch("https://api.railradar.in/v1/lookup/trains", {
    headers: {
      Authorization: `Bearer ${API_KEY}`,
    },
  });

  if (!response.ok) {
    throw new Error("Failed to fetch trains");
  }

  const result = await response.json();

  // result.data is an object
  // {
  //   "12002": "New Delhi - Bhopal Shatabdi Express",
  //   "12919": "Malwa Express",
  //   ...
  // }

  const filteredTrains = Object.entries(result.data)
    .map(([number, name]) => ({
      number,
      name,
    }))
    .filter(
      (train) =>
        train.number.includes(search) ||
        train.name.toLowerCase().includes(search),
    );
  console.log(filteredTrains);
  return filteredTrains;
};

